MILESTONES = [f"M{i}" for i in range(9)]
TYPES = ["feature", "change", "fix", "decision", "fallback", "blocked", "spike"]


def load_entries(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()]


def parse_requirements(path: Path) -> list[dict]:
    if not path.exists():
        return []
    out = []
    for m in re.finditer(r"^### (FR-\d+) (.+)$", path.read_text(), re.M):
        out.append({"id": m.group(1), "title": m.group(2).split(" — ")[0].replace("`", "").strip()})
    return out


def parse_progress(path: Path) -> dict[str, str]:
    """Return {task id: status} from the status table rows in PROGRESS.md."""
    if not path.exists():
        return {}
    return {m.group(1): m.group(2) for m in re.finditer(
        r"^\| (T\d+\.\d+) \| M\d \| (\w+) \|", path.read_text(), re.M)}


def _node(entry_id: str) -> str:
    return entry_id.replace("-", "")


def _safe(text: str, limit: int = 44) -> str:
    text = re.sub(r'["\[\]{}()<>|`#]', " ", text).strip()
    return text[:limit - 1] + "…" if len(text) > limit else text


def mermaid(entries: list[dict]) -> str:
    lines = ["```mermaid", "flowchart LR"]
    for ms in MILESTONES:
        group = [e for e in entries if e["milestone"] == ms]
        if group:
            lines.append(f"  subgraph {ms}")
            lines += [f'    {_node(e["id"])}["{e["id"]} {_safe(e["title"])}"]' for e in group]
            lines.append("  end")
    known = {e["id"] for e in entries}
    for e in entries:
        links, me = e.get("links", {}), _node(e["id"])
        for o in links.get("caused_by", []):
            if o in known:
                lines.append(f"  {_node(o)} -->|caused| {me}")
        for o in links.get("supersedes", []):
            if o in known:
                lines.append(f"  {me} -.->|replaces| {_node(o)}")
        for o in links.get("related", []):
            if o in known:
                lines.append(f"  {me} -.- {_node(o)}")
    lines.append("```")
    return "\n".join(lines)


def render_markdown(entries: list[dict]) -> str:
    out = ["# LegacyGuard dev log", "",
           "Generated by `tools/devlog_viz.py` from `docs/devlog.jsonl`. Do not edit by hand. "
           "For the interactive view, open `docs/devlog.html` in a browser.", "",
           "## Relationship map", "",
           "Solid arrows mean one entry caused another. Dashed arrows labeled \"replaces\" mean "
           "one entry supersedes another. Dotted lines mean the entries are related.", "",
           mermaid(entries), "", "## Summary", ""]
    used_ms = [m for m in MILESTONES if any(e["milestone"] == m for e in entries)]
    out.append("| Milestone | " + " | ".join(TYPES) + " | Total |")
    out.append("| --- |" + " --- |" * (len(TYPES) + 1))
    for ms in used_ms:
        c = Counter(e["type"] for e in entries if e["milestone"] == ms)
        out.append(f"| {ms} | " + " | ".join(str(c.get(t, 0)) for t in TYPES) + f" | {sum(c.values())} |")
    c = Counter(e["type"] for e in entries)
    out.append("| **All** | " + " | ".join(f"**{c.get(t, 0)}**" for t in TYPES) + f" | **{len(entries)}** |")
    out += ["", "## Entries, newest first", ""]

    def fmt(value) -> str:
        if isinstance(value, list):
            return ", ".join(f"`{v}`" for v in value) or "none"
        return str(value) if value else "none"

    for e in reversed(entries):
        out += [f"### {e['id']} · {e['title']}", "",
                f"**{e['type']}** · {e['milestone']} · {e['task']} · {e['time']} · commit `{e.get('commit') or 'pending'}`", "",
                f"- **Context:** {fmt(e['context'])}", f"- **What:** {fmt(e['what'])}", f"- **Why:** {fmt(e['why'])}"]
        if e.get("root_cause"):
            out.append(f"- **Root cause:** {e['root_cause']}")
        out.append(f"- **Impact:** {fmt(e['impact'])}")
        out.append(f"- **Files:** {fmt(e['files'])}")
        for key, label in [("requirements", "Requirements"), ("decisions", "Decisions"),
                           ("open_questions", "Open questions"), ("tests", "Tests")]:
            out.append(f"- **{label}:** {fmt(e['refs'].get(key, []))}")
        for key, label in [("caused_by", "Caused by"), ("supersedes", "Supersedes"), ("related", "Related")]:
            if e["links"].get(key):
                out.append(f"- **{label}:** {fmt(e['links'][key])}")
        out += ["- **Evidence:**", "", "```text", str(e.get("evidence") or "none"), "```", ""]
    return "\n".join(out) + "\n"


