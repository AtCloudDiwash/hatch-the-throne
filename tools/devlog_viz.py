def render_html(entries, requirements, progress) -> str:
    data = {"entries": entries, "requirements": requirements, "progress": progress,
            "types": TYPES, "milestones": MILESTONES}
    blob = json.dumps(data, ensure_ascii=False).replace("<", "\\u003c")
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>LegacyGuard dev log</title><style>{CSS}</style></head><body>
<header><h1>LegacyGuard dev log</h1><p>{len(entries)} entries, generated from docs/devlog.jsonl</p></header>
<nav role="tablist"><button data-v="timeline" role="tab">Timeline</button><button data-v="map" role="tab">Relationship map</button><button data-v="matrix" role="tab">Coverage matrix</button></nav>
<div class="bar"><fieldset id="ftype"><legend>Type</legend></fieldset><fieldset id="fms"><legend>Milestone</legend></fieldset></div>
<main><div id="view"></div><aside></aside></main><div id="tip"></div>
<script type="application/json" id="data">{blob}</script>
<script>{JS}</script></body></html>
"""


def generate(log: Path, requirements: Path, progress: Path, md: Path, out_html: Path) -> None:
    entries = load_entries(log)
    md.parent.mkdir(parents=True, exist_ok=True)
    md.write_text(render_markdown(entries))
    out_html.write_text(render_html(entries, parse_requirements(requirements), parse_progress(progress)))


def main() -> None:
    root = Path(__file__).resolve().parent.parent / "docs"
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--log", type=Path, default=root / "devlog.jsonl")
    ap.add_argument("--requirements", type=Path, default=root / "REQUIREMENTS.md")
    ap.add_argument("--progress", type=Path, default=root / "PROGRESS.md")
    ap.add_argument("--md", type=Path, default=root / "DEVLOG.md")
    ap.add_argument("--html", type=Path, default=root / "devlog.html")
    a = ap.parse_args()
    generate(a.log, a.requirements, a.progress, a.md, a.html)
    print(f"wrote {a.md} and {a.html} ({html.escape(str(len(load_entries(a.log))))} entries)")


if __name__ == "__main__":
    main()
