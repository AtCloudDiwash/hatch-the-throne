#!/usr/bin/env python3
"""Generate a billing-api git repo with planted history from demo/billing-api-src (T2.3, D-037)."""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "billing-api-src"
VENV = HERE / ".billing-venv"
MARKER = ".billing-generated"

# Commit i (1-based) of 17 always changes billing/fees.py. These leave out the coupled files.
NO_RATES = {4, 9, 13}          # 14 of 17 also change db/rates.sql: 82%
NO_CLOSE = {2, 4, 6, 9, 11}    # 12 of 17 also change jobs/close_month.py: 71%
MESSAGES = ["Adjust late fee schedule", "Fee tweak for plus tier", "Q2 rate update", "Clarify fee rounding note", "Q3 rate update",
            "Rate correction from finance", "Add premier rate", "Rate update after audit", "Fee docstring cleanup", "Q4 rate update",
            "Early-pay rate change", "New year rates", "Fee constant rename", "Q1 rate update", "Finance rate correction",
            "Mid-year rates", "Current rate table"]
NOISE = {3: "Add dunning levels doc", 6: "Note statement format", 9: "Note void rules", 12: "Note credit limits",
         14: "Note tier grace days", 16: "Note audit export"}


def run(dest: Path, *args: str, date: str = "2025-01-01T09:00:00") -> None:
    env = {**os.environ, "GIT_AUTHOR_NAME": "Billing Team", "GIT_AUTHOR_EMAIL": "billing@example.test",
           "GIT_COMMITTER_NAME": "Billing Team", "GIT_COMMITTER_EMAIL": "billing@example.test",
           "GIT_AUTHOR_DATE": date, "GIT_COMMITTER_DATE": date}
    subprocess.run(["git", "-C", str(dest), *args], check=True, capture_output=True, env=env)


def sub_file(path: Path, pattern: str, repl: str) -> None:
    text, n = re.subn(pattern, repl, path.read_text())
    if not n:
        raise RuntimeError(f"pattern {pattern} not found in {path}")
    path.write_text(text)


def set_fees(dest: Path, rev: int) -> None:
    sub_file(dest / "billing/fees.py", r"RATE_TABLE_REVISION = \d+", f"RATE_TABLE_REVISION = {rev}")


def set_rates(dest: Path, rev: int) -> None:
    sub_file(dest / "db/rates.sql", r"-- revision \d+", f"-- revision {rev}")
    sub_file(dest / "db/rates.sql", r", \d+\);", f", {rev});")


def set_close(dest: Path, version: int) -> None:
    sub_file(dest / "jobs/close_month.py", r"FEE_RUN_VERSION = \d+", f"FEE_RUN_VERSION = {version}")


def ensure_venv() -> None:
    """Shared dependencies for every generated copy, so a fresh clone needs only this script."""
    if not (VENV / "bin" / "python").exists():
        subprocess.run(["python3", "-m", "venv", str(VENV)], check=True)
        subprocess.run([str(VENV / "bin" / "python"), "-m", "pip", "install", "-q", "-r", str(SRC / "requirements.txt")], check=True)


def build(dest: Path, traps: bool = True, guard: bool = True) -> None:
    if dest.exists():
        if not (dest / MARKER).exists():
            raise SystemExit(f"refusing to replace {dest}: it was not generated by this script")
        shutil.rmtree(dest)
    ignore = shutil.ignore_patterns("__pycache__", ".pytest_cache", "*.pyc", "billing.db", ".venv")
    shutil.copytree(SRC, dest, ignore=ignore)
    if not traps:
        (dest / "TRAPS.md").unlink()
    if not guard:
        shutil.rmtree(dest / ".legacyguard")
    subprocess.run(["git", "init", "-q", "-b", "main", str(dest)], check=True)
    (dest / ".git" / "info" / "exclude").write_text(f"{MARKER}\n")
    (dest / MARKER).write_text("generated by demo/build_billing_repo.py\n")
    ensure_venv()
    (dest / ".venv").symlink_to(VENV)

    final_notes = (dest / "README.md").read_text()
    rates_rev, close_rev = 3, 0
    set_fees(dest, 0), set_rates(dest, rates_rev), set_close(dest, close_rev)
    run(dest, "add", "-A")
    run(dest, "commit", "-qm", "Import billing service")
    notes = final_notes
    for i, message in enumerate(MESSAGES, 1):
        date = f"2025-{(i % 12) + 1:02d}-{(i % 27) + 1:02d}T10:00:00"
        set_fees(dest, i)
        if i not in NO_RATES:
            rates_rev += 1
            set_rates(dest, rates_rev)
        if i not in NO_CLOSE:
            close_rev += 1
            set_close(dest, close_rev)
        run(dest, "add", "-A")
        run(dest, "commit", "-qm", message, date=date)
        if i in NOISE:
            notes += f"\n{NOISE[i]}.\n"
            (dest / "README.md").write_text(notes)
            run(dest, "add", "-A")
            run(dest, "commit", "-qm", NOISE[i], date=date)
    # The source files carry the final revisions, so this ends identical to demo/billing-api-src.
    assert (dest / "billing/fees.py").read_text() == (SRC / "billing/fees.py").read_text()
    assert (dest / "db/rates.sql").read_text() == (SRC / "db/rates.sql").read_text()
    assert (dest / "jobs/close_month.py").read_text() == (SRC / "jobs/close_month.py").read_text()


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dest", type=Path, default=HERE / "billing-api")
    ap.add_argument("--no-traps", action="store_true", help="leave out TRAPS.md (for A/B runs)")
    ap.add_argument("--no-guard", action="store_true", help="leave out .legacyguard/ (guard-off A/B runs)")
    a = ap.parse_args()
    build(a.dest.resolve(), traps=not a.no_traps, guard=not a.no_guard)
    print(a.dest)
